class imovel:
 def init(self,tipo,valor_base):
  self.tipo = tipo
  self.valor_base = valor_base

class Apartamento(imovel):
    def _init_(self, quartos, tem_garagem, tem_criancas):
        super()._init_("Apartamento", 700.00)
        self.quartos = quartos
        self.tem_garagem = tem_garagem
        self.tem_criancas = tem_criancas

    def calcular_aluguel_mensal(self):
        total = self.valor_base
        if self.quartos == 2:
            total += 200.00
        if self.tem_garagem:
            total += 300.00
        if not self.tem_criancas:
            total *= 0.95
        return round(total, 2)

class Casa(imovel):
    def _init_(self, quartos, tem_garagem):
        super()._init_("Casa", 900.00)
        self.quartos = quartos
        self.tem_garagem = tem_garagem

    def calcular_aluguel_mensal(self):
        total = self.valor_base
        if self.quartos == 2:
            total += 250.00
        if self.tem_garagem:
            total += 300.00
        return round(total, 2)


class Estudio(imovel):
    def _init_(self, qtd_vagas):
        super()._init_("Estúdio", 1200.00)
        self.qtd_vagas = qtd_vagas

    def calcular_aluguel_mensal(self):
        total = self.valor_base
        if self.qtd_vagas > 0:
            vagas_extras = max(0, self.qtd_vagas - 2)
            total += 250.00 + (vagas_extras * 60.00)
        return round(total, 2)

import csv


class Orcamento:
    TAXA_CONTRATUAL = 2000.00

    def __init__(self, imovel: imovel, parcelas_taxa: int):
        self.imovel = imovel
        self.parcelas_taxa = parcelas_taxa
        self.valor_parcela_taxa = round(self.TAXA_CONTRATUAL / parcelas_taxa, 2)

    def exibir_resumo(self):
        aluguel = self.imovel.calcular_aluguel_mensal()
        print("\n" + "=" * 50)
        print("      RESUMO DO ORÇAMENTO - R.M IMÓVEIS")
        print("=" * 50)
        print(f"Categoria do Imóvel   : {self.imovel.tipo}")
        print(f"Aluguel Mensal Final  : R$ {aluguel:.2f}")
        print("-" * 50)
        print("CONDIÇÕES CONTRATUAIS (Custo Separado):")
        print(f"Taxa Contratual Total : R$ {self.TAXA_CONTRATUAL:.2f}")
        print(f"Parcelamento          : {self.parcelas_taxa}x de R$ {self.valor_parcela_taxa:.2f}")
        print("=" * 50)

    def gerar_csv(self, nome_arquivo="projecao_12_meses.csv"):
        aluguel = self.imovel.calcular_aluguel_mensal()
        with open(nome_arquivo, mode="w", newline="", encoding="utf-8-sig") as arquivo:
            escritor = csv.writer(arquivo, delimiter=";")
            escritor.writerow([
                "Mês",
                "Imóvel",
                "Aluguel Mensal (R$)",
                "Parcela Taxa Contratual (R$)",
                "Total no Mês (R$)"
            ])
            for mes in range(1, 13):
                parcela = self.valor_parcela_taxa if mes <= self.parcelas_taxa else 0.00
                total_mes = round(aluguel + parcela, 2)
                escritor.writerow([
                    f"Mês {mes:02d}",
                    self.imovel.tipo,
                    f"{aluguel:.2f}".replace(".", ","),
                    f"{parcela:.2f}".replace(".", ","),
                    f"{total_mes:.2f}".replace(".", ",")
                ])
        print(f"\n[OK] Arquivo '{nome_arquivo}' gerado com sucesso!")


